#!/usr/bin/env python3
"""Compare redacted, independently prepared recovery manifests.

This is NOT an independent DB/media restore: no data is read and no backup
is created. Both files must be root-owned, mode 0600, and be generated by
independent, approved source/restore operators with agreed keyed identifiers.
"""
import argparse
import json
import os
from pathlib import Path
import re
import stat
import sys

MAX_MANIFEST=1048576
HEXDIGEST=re.compile(r"^[0-9a-f]{64}$")


class Blocked(Exception):
    pass


def private_manifest(path):
    path=Path(path)
    if not path.is_absolute() or path.is_symlink():
        raise Blocked("MANIFEST_PATH_UNSAFE")
    info=path.lstat()
    if not stat.S_ISREG(info.st_mode) or info.st_uid!=0 or \
       (stat.S_IMODE(info.st_mode)&0o077) or info.st_size>MAX_MANIFEST:
        raise Blocked("MANIFEST_PERMISSIONS_OR_SIZE_UNSAFE")
    flags=os.O_RDONLY | getattr(os,"O_NOFOLLOW",0)
    fd=os.open(path,flags)
    try:
        s=os.fstat(fd)
        if not stat.S_ISREG(s.st_mode) or s.st_size>MAX_MANIFEST:
            raise Blocked("MANIFEST_RACE")
        data=os.read(fd,MAX_MANIFEST+1)
    finally:
        os.close(fd)
    if len(data)>MAX_MANIFEST:
        raise Blocked("MANIFEST_OVERSIZED")
    obj=json.loads(data.decode("utf-8"))
    if not isinstance(obj,dict):
        raise Blocked("MANIFEST_FORMAT")
    return obj


def valid_mapping(mapping,value_validator):
    if not isinstance(mapping,dict) or len(mapping)>50000:
        return False
    for k,v in mapping.items():
        if not isinstance(k,str) or not HEXDIGEST.fullmatch(k) or not value_validator(v):
            return False
    return True


def validate(m):
    if m.get("schema_version")!=1:
        raise Blocked("MANIFEST_SCHEMA_VERSION")
    db=m.get("database_table_counts")
    media=m.get("media_object_sha256")
    if not valid_mapping(db,lambda x: isinstance(x,int) and not isinstance(x,bool) and x>=0):
        raise Blocked("DB_COUNTS_FORMAT")
    if not valid_mapping(media,lambda x: isinstance(x,str) and bool(HEXDIGEST.fullmatch(x))):
        raise Blocked("MEDIA_DIGEST_FORMAT")
    if len(db)<1 or len(media)<1:
        raise Blocked("EMPTY_DB_OR_MEDIA")
    for key in ("ownership_integrity_hmac","migration_state_hmac","release_artifact_sha256"):
        if not isinstance(m.get(key),str) or not HEXDIGEST.fullmatch(m[key]):
            raise Blocked("INTEGRITY_FIELDS_MISSING")
    expected={"schema_version","database_table_counts","media_object_sha256",
              "ownership_integrity_hmac","migration_state_hmac",
              "release_artifact_sha256"}
    if set(m)!=expected:
        raise Blocked("UNEXPECTED_MANIFEST_CONTENT")
    return {"tables":len(db),"media":len(media),"rows":sum(db.values())}


def compare(source,restored):
    a=validate(source)
    b=validate(restored)
    return a,b,source==restored


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--compare",action="store_true",required=True)
    parser.add_argument("--source-manifest",required=True)
    parser.add_argument("--restored-manifest",required=True)
    args=parser.parse_args()
    if os.geteuid()!=0:
        raise Blocked("ROOT_REQUIRED")
    src=Path(args.source_manifest)
    dst=Path(args.restored_manifest)
    if src==dst or src.resolve()==dst.resolve():
        raise Blocked("MANIFESTS_MUST_BE_SEPARATE")
    a,b,same=compare(private_manifest(src),private_manifest(dst))
    print("MCP_RECONCILIATION_SOURCE_TABLES="+str(a["tables"]))
    print("MCP_RECONCILIATION_RESTORE_TABLES="+str(b["tables"]))
    print("MCP_RECONCILIATION_SOURCE_MEDIA_OBJECTS="+str(a["media"]))
    print("MCP_RECONCILIATION_RESTORE_MEDIA_OBJECTS="+str(b["media"]))
    print("MCP_RECONCILIATION_MANIFEST_MATCH="+("YES" if same else "NO"))
    print("MCP_RECONCILIATION_CUSTOMER_CONTENT=NOT_READ")
    print("MCP_RECONCILIATION_SOURCE_PROVENANCE=NOT_INDEPENDENTLY_VERIFIED")
    print("MCP_RESTORE_ACCEPTANCE=BLOCKED_PENDING_INDEPENDENT_REVIEW")
    print("MCP_PRODUCTION_RELEASE=BLOCKED")
    if not same:
        raise Blocked("MANIFEST_MISMATCH")


if __name__=="__main__":
    try:
        main()
    except (Blocked,OSError,ValueError,UnicodeError,json.JSONDecodeError):
        print("MCP_RECONCILIATION=BLOCKED_PRIVATE_OPERATOR_REVIEW")
        sys.exit(1)
