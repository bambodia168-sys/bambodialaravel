#!/usr/bin/env bash
# Bambodia Step 34B.6 - offline restoration rehearsal of the preserved QA host.
# Extract only into a restricted disposable directory under /var/backups.
# Never change the existing site, active vhost, TLS keys, QA DB, or source.
set -Eeuo pipefail
set +x
umask 077

HOST="oauth-qa.bambodia.com"
SITE="/www/wwwroot/$HOST"
VHOST="/www/server/panel/vhost/nginx/$HOST.conf"
QA="/var/lib/bambodia-oauth-browser-qa"
QA_SHA="34e86fbbdfcbe56e5e28e0286a47ba2309e48455"
BACKUP="/var/backups/bambodia-oauth-qa-preserve.6JJJAhXJ"
BACKUP_PARENT="/var/backups"
INDEX_HASH="0bae6089419ea8f95d7ddf86ba40a6b6c8ae6fca852dd9b70351f869e19df27b"
VHOST_HASH="c5e89eb3a29e3e923fb1a82d47b0add50198af45d673f1235956ca7dbeb61c94"
CNF="/root/bambodia-oauth-browser-qa.cnf"
MYSQL="/www/server/mysql/bin/mysql"
DB="bambodia_oauthqa_browser"
WORK=""

cleanup() {
  # Only remove the particular scratch directory generated by mktemp below.
  if [[ -n "$WORK" && "$WORK" =~ ^/var/backups/bambodia-oauth-restore-qa\.[A-Za-z0-9]{8}$ &&
        -d "$WORK" && ! -L "$WORK" ]]; then
    rm -rf --one-file-system -- "$WORK"
  fi
}
trap cleanup EXIT

echo '========== CHECK ROOT, QA, AND EXISTING SITE =========='
test "$(id -u)" -eq 0
for tool in git tar sha256sum stat python3 mktemp find rm; do
  command -v "$tool" >/dev/null
done
test -d "$BACKUP_PARENT" && test ! -L "$BACKUP_PARENT"
test -d "$BACKUP" && test ! -L "$BACKUP"
test "$(realpath -e "$BACKUP")" = "$BACKUP"
test "$(stat -c '%u:%a' "$BACKUP")" = "0:700"
test -d "$SITE" && test ! -L "$SITE"
test "$(realpath -e "$SITE")" = "$SITE"
test -f "$SITE/index.html" && test ! -L "$SITE/index.html"
test -f "$VHOST" && test ! -L "$VHOST"
test "$(sha256sum "$SITE/index.html" | awk '{print $1}')" = "$INDEX_HASH"
test "$(sha256sum "$VHOST" | awk '{print $1}')" = "$VHOST_HASH"
test -d "$QA/.git" && test ! -L "$QA"
test "$(realpath -e "$QA")" = "$QA"
test "$(git -C "$QA" rev-parse HEAD)" = "$QA_SHA"
test -z "$(git -C "$QA" status --porcelain --untracked-files=no)"
test -f "$QA/.env" && test ! -L "$QA/.env"
grep -Fxq 'APP_URL=https://oauth-browser-qa.invalid' "$QA/.env"
test -s "$QA/public/build/manifest.json"

for part in site.tar nginx-vhost.conf public-cert-sha256.txt RESTORE_NOTES.txt SHA256SUMS; do
  test -f "$BACKUP/$part" && test ! -L "$BACKUP/$part"
  test "$(stat -c '%u:%a' "$BACKUP/$part")" = "0:600"
done
test "$(sha256sum "$BACKUP/nginx-vhost.conf" | awk '{print $1}')" = "$VHOST_HASH"
(
  cd "$BACKUP"
  sha256sum --status -c SHA256SUMS
)
echo 'BACKUP_34B5_CHECKSUMS_AND_PERMISSIONS=PASS'

test -f "$CNF" && test ! -L "$CNF"
test "$(stat -c '%u:%a' "$CNF")" = "0:600"
test -x "$MYSQL"
QA_MYSQL() {
  "$MYSQL" --defaults-extra-file="$CNF" --protocol=TCP \
    --host=127.0.0.1 --batch --skip-column-names "$DB" "$@"
}
test "$(QA_MYSQL -e 'SELECT DATABASE()')" = "$DB"
test "$(QA_MYSQL -e 'SELECT COUNT(*) FROM users')" = 1
test "$(QA_MYSQL -e 'SELECT COUNT(*) FROM oauth_clients')" = 1
test "$(QA_MYSQL -e "SELECT COUNT(*) FROM users WHERE email='oauth-admin@oauth-browser-qa.invalid' AND role='super_admin' AND account_status='active'")" = 1
for table in oauth_auth_codes oauth_access_tokens oauth_refresh_tokens; do
  test "$(QA_MYSQL -e "SELECT COUNT(*) FROM $table WHERE revoked=0")" = 0
done
echo 'QA_SOURCE_AND_DATABASE_BASELINE=PASS'
echo 'ACTIVE_OAUTH_GRANTS=0'

echo '========== VALIDATE ARCHIVE SAFETY BEFORE EXTRACTION =========='
python3 - "$BACKUP/site.tar" "$HOST" "$INDEX_HASH" <<'PY'
import hashlib
import pathlib
import sys
import tarfile

archive, root, expected_hash = sys.argv[1:]
names = set()
count_files = 0
with tarfile.open(archive, mode="r:") as tf:
    members = tf.getmembers()
    assert len(members) == 9, "Unexpected archive member count"
    for member in members:
        name = pathlib.PurePosixPath(member.name)
        assert not name.is_absolute() and ".." not in name.parts
        assert name.parts and name.parts[0] == root
        assert member.isfile() or member.isdir(), "Special file or link in archive"
        assert member.name not in names, "Duplicate archive member"
        names.add(member.name)
        if member.isfile():
            count_files += 1
            assert member.size <= 32 * 1024 * 1024, "Oversized archive member"
    index = tf.extractfile(root + "/index.html")
    assert index is not None, "No index in archive"
    assert hashlib.sha256(index.read()).hexdigest() == expected_hash
    print("ARCHIVED_MEMBER_COUNT=" + str(len(members)))
    print("ARCHIVED_REGULAR_FILE_COUNT=" + str(count_files))
print("ARCHIVE_EXTRACTION_SAFETY=PASS")
PY

echo '========== REQUIRE SCRATCH-ONLY RESTORE APPROVAL =========='
test -c /dev/tty
echo 'Extracts a copy to a disposable root-only directory; then deletes only that copy.'
echo 'Does not change the live site, vhost, certificate, or OAuth QA environment.'
printf 'Type RESTORE-REHEARSAL-SCRATCH-ONLY to proceed: ' > /dev/tty
IFS= read -r approval < /dev/tty
if [ "$approval" != "RESTORE-REHEARSAL-SCRATCH-ONLY" ]; then
  echo 'STEP34B6_APPROVAL=DECLINED'
  exit 1
fi
echo 'STEP34B6_APPROVAL=PASS'

echo '========== RESTORE INTO RESTRICTED SCRATCH =========='
WORK="$(mktemp -d "$BACKUP_PARENT/bambodia-oauth-restore-qa.XXXXXXXX")"
test -d "$WORK" && test ! -L "$WORK"
test "$(stat -c '%u:%a' "$WORK")" = "0:700"
mkdir -m 700 "$WORK/extracted"
tar --no-same-owner -xf "$BACKUP/site.tar" -C "$WORK/extracted"

python3 - "$BACKUP/site.tar" "$WORK/extracted" "$HOST" <<'PY'
import hashlib
from pathlib import Path
import sys
import tarfile

archive, folder, host = sys.argv[1:]
folder = Path(folder)
count_files = 0
with tarfile.open(archive, mode="r:") as tf:
    for member in tf.getmembers():
        restored = folder / member.name
        assert restored.exists() and not restored.is_symlink()
        if member.isfile():
            count_files += 1
            source = tf.extractfile(member)
            assert source is not None
            original_sha = hashlib.sha256(source.read()).hexdigest()
            digest = hashlib.sha256()
            with restored.open("rb") as handle:
                for block in iter(lambda: handle.read(1024 * 1024), b""):
                    digest.update(block)
            assert original_sha == digest.hexdigest(), "Extracted file hash mismatch"
        else:
            assert restored.is_dir()
    assert (folder / host / "index.html").is_file()
print("RESTORED_MEMBER_HASH_COMPARISON=PASS")
print("RESTORED_REGULAR_FILES_VERIFIED=" + str(count_files))
PY

echo '========== CONFIRM LIVE ENVIRONMENT REMAINS UNCHANGED =========='
test "$(sha256sum "$SITE/index.html" | awk '{print $1}')" = "$INDEX_HASH"
test "$(sha256sum "$VHOST" | awk '{print $1}')" = "$VHOST_HASH"
test "$(git -C "$QA" rev-parse HEAD)" = "$QA_SHA"
test -z "$(git -C "$QA" status --porcelain --untracked-files=no)"

echo 'STEP34B6_OFFLINE_RESTORE_REHEARSAL=PASS'
echo 'EXISTING_WEBSITE_AND_VHOST=UNCHANGED'
echo 'CERTIFICATE_PRIVATE_KEYS=NOT_READ_OR_COPIED'
echo 'LIVE_RESTORE_OR_ROLLBACK=NOT_PERFORMED'
echo 'EXISTING_HOSTNAME_REUSE_APPROVAL=NOT_GRANTED'
echo 'PUBLIC_OAUTH_ENDPOINT=NOT_DEPLOYED'
echo 'QA_DATABASE_WRITES=NONE'
echo 'DNS_NGINX_TLS_CHANGES=NONE'
echo 'GITHUB_MAIN_AND_PRODUCTION=UNCHANGED'
